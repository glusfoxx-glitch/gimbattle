import assert from 'node:assert/strict';
import { register } from 'node:module';
register('./peer-hooks.mjs', import.meta.url);
globalThis.Worker = class { terminate() {} };
const { createHostSocket, createGuestSocket } = await import('../public/gim/client/p2p.js');
const { peers, PeerChannel } = await import('./peer-fake.mjs');
const { MAX_PLAYERS } = await import('../public/gim/shared/constants.js');
assert.equal(MAX_PLAYERS, 32);
const host = createHostSocket('many');
const peer = peers.at(-1);
let opened = 0;
const messages = [];
host.onopen = () => { opened++; host.send(JSON.stringify({ t: 'join', name: 'Host', brawler: 0 })); };
host.onmessage = data => { if (typeof data === 'string') messages.push(JSON.parse(data)); };
peer.emit('open');
await Promise.resolve();
const channels = [];
for (let i = 1; i < 32; i++) {
  const c = new PeerChannel(); channels.push(c); peer.emit('connection', c);
  c.emit('data', JSON.stringify({ t: 'join', name: `P${i}`, brawler: i % 9 }));
  assert.equal(JSON.parse(c.messages[0]).slot, i);
}
peer.emit('open'); // signaling recovery must not replace the room
assert.equal(opened, 1);
channels[4].close();
const replacement = new PeerChannel(); peer.emit('connection', replacement);
replacement.emit('data', JSON.stringify({ t: 'join', name: 'Replacement', brawler: 0 }));
assert.equal(JSON.parse(replacement.messages[0]).slot, 5);
const overflow = new PeerChannel(); peer.emit('connection', overflow);
overflow.emit('data', JSON.stringify({ t: 'join', name: 'Overflow', brawler: 0 }));
assert.match(JSON.parse(overflow.messages[0]).message, /32/);
assert.equal(messages.filter(m => m.t === 'welcome').length, 1);
host.close();
const guest = createGuestSocket('many');
let failures = 0; let guestOpens = 0;
guest.onfail = () => failures++;
guest.onopen = () => guestOpens++;
const old = peers.at(-1);
old.emit('error', { type: 'network' });
const fresh = peers.at(-1);
assert.notEqual(fresh, old);
assert.equal(failures, 0);
old.emit('error', { type: 'peer-unavailable' });
fresh.emit('open'); fresh.connections[0].emit('open');
assert.equal(guestOpens, 1);
fresh.emit('error', { type: 'network' });
assert.equal(failures, 0);
guest.close();
console.log('Passed: 32 players, reconnect preservation, slot reuse, capacity message, stale-event retirement and guest recovery.');